//! What a chip is called, and the files a submission is made of.

use std::fmt;

use ferrite_lithic_rtl::Module;

use crate::pins::{Error, PinMap};
use crate::wrapper::{pinout, top_module_name, wrapper};

/// The metadata of a submission.
///
/// # The name is not decoration
///
/// `tt_um_<user>_<project>` is the name of the cell on the die, the name the
/// shuttle documentation indexes, and the name the submitter is identified by.
/// It has to be unique across the shuttle, which is why the user is in it.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct Chip {
    /// The submitter's user name, as on the shuttle.
    pub user: String,
    /// The project's name, as a slug.
    pub project: String,
    /// The project's title, for the datasheet.
    pub title: String,
    /// The author's name, for the datasheet.
    pub author: String,
    /// One line describing the project.
    pub description: String,
    /// The clock frequency in hertz, or zero if it does not apply.
    pub clock_hz: u32,
    /// How many tiles the design occupies, as columns by rows.
    pub tiles: (u32, u32),
    /// The core module's reset port.
    ///
    /// Active high and synchronous, because that is what the DSL's registers
    /// take. The die's `rst_n` is active low, and the wrapper inverts it.
    pub reset_port: String,
}

impl Chip {
    /// The number of tiles the design occupies.
    #[must_use]
    pub const fn tile_count(&self) -> u32 {
        self.tiles.0 * self.tiles.1
    }
}

/// The files a submission is made of.
#[derive(Clone, Debug)]
pub struct Project {
    /// The wrapper's Verilog, the top module.
    pub top: String,
    /// The core module's Verilog.
    pub core: String,
    /// The `info.yaml` the build reads.
    pub info_yaml: String,
    /// The `docs/info.md` the shuttle documentation is generated from.
    pub docs_info: String,
}

/// Build every file of a submission.
///
/// # Errors
///
/// Whatever [`wrapper`] reports: a pin that names a port the module does not
/// have, a port that is not one bit wide, a module with no clock, or a pin map
/// that does not fit the die.
pub fn project(
    chip: &Chip,
    core: &Module,
    pins: &PinMap,
    source_files: &[&str],
) -> Result<Project, BuildError> {
    let top = wrapper(chip, core, pins)?;
    let core_text = core.emit().map_err(|e| BuildError::Core(e.to_string()))?;
    Ok(Project {
        info_yaml: info_yaml(chip, pins, source_files),
        docs_info: docs_info(chip, pins),
        top,
        core: core_text,
    })
}

/// The `info.yaml` the Tiny Tapeout build reads.
///
/// The shape is fixed by the build: `project`, `pinout` and `yaml_version`. The
/// pinout section is *"for the datasheet/website"* and its comments say to use
/// descriptive names, which is why the pin names come from the design and not
/// from the port names.
#[must_use]
pub fn info_yaml(chip: &Chip, pins: &PinMap, source_files: &[&str]) -> String {
    let mut out = String::new();
    out.push_str("# Generated by ferrite-lithic-chip. Do not edit; regenerate from the design.\n");
    out.push_str("# Tiny Tapeout project information\n");
    out.push_str("project:\n");
    out.push_str(&format!("  title:        \"{}\"\n", chip.title));
    out.push_str(&format!("  author:       \"{}\"\n", chip.author));
    out.push_str("  discord:      \"\"\n");
    out.push_str(&format!("  description:  \"{}\"\n", chip.description));
    out.push_str("  language:     \"Verilog\"\n");
    out.push_str(&format!("  clock_hz:     {}\n", chip.clock_hz));
    out.push_str(&format!("  tiles: \"{}x{}\"\n", chip.tiles.0, chip.tiles.1));
    out.push_str(&format!("  top_module:  \"{}\"\n", top_module_name(chip)));
    out.push_str("  source_files:\n");
    for file in source_files {
        out.push_str(&format!("    - \"{file}\"\n"));
    }
    out.push('\n');
    out.push_str(
        "# The pinout of your project. Leave unused pins blank. DO NOT delete or add any pins.\n",
    );
    out.push_str("# This section is for the datasheet/website. Use descriptive names (e.g., RX, TX, MOSI, SCL, SEG_A, etc.).\n");
    out.push_str("pinout:\n");
    for (group, names) in pinout(pins) {
        match group {
            "ui" => out.push_str("  # Inputs\n"),
            "uo" => out.push_str("  # Outputs\n"),
            _ => out.push_str("  # Bidirectional pins\n"),
        }
        for (index, name) in names.iter().enumerate() {
            out.push_str(&format!("  {group}[{index}]: \"{name}\"\n"));
        }
    }
    out.push('\n');
    out.push_str("# Do not change!\n");
    out.push_str("yaml_version: 6\n");
    out
}

/// The `docs/info.md` the shuttle documentation is generated from.
#[must_use]
pub fn docs_info(chip: &Chip, pins: &PinMap) -> String {
    let mut out = String::new();
    out.push_str(&format!("# {}\n\n", chip.title));
    out.push_str(&format!("{}\n\n", chip.description));
    out.push_str("## Author\n\n");
    out.push_str(&format!("{}\n\n", chip.author));
    out.push_str("## Pinout\n\n");
    for (group, names) in pinout(pins) {
        let heading = match group {
            "ui" => "Dedicated inputs",
            "uo" => "Dedicated outputs",
            _ => "Bidirectional pins",
        };
        out.push_str(&format!("### {heading}\n\n"));
        for (index, name) in names.iter().enumerate() {
            if name.is_empty() {
                out.push_str(&format!("- `{group}[{index}]`: unused\n"));
            } else {
                out.push_str(&format!("- `{group}[{index}]`: {name}\n"));
            }
        }
        out.push('\n');
    }
    out.push_str("## How it works\n\n");
    out.push_str(&format!(
        "The design occupies {} tiles of the allocation and is built from a Rust hardware\n\
         DSL whose output is Verilog. See the repository for the source.\n",
        chip.tile_count()
    ));
    out
}

/// Write a submission to a directory.
///
/// The layout is the one the Tiny Tapeout template uses: `src/` for the
/// Verilog, `docs/info.md` for the documentation, and `info.yaml` at the top.
///
/// # Errors
///
/// [`BuildError::Io`] if a file cannot be written.
pub fn write_project(dir: &std::path::Path, project: &Project) -> Result<(), BuildError> {
    std::fs::create_dir_all(dir.join("src"))?;
    std::fs::create_dir_all(dir.join("docs"))?;
    std::fs::write(dir.join("src").join("project.v"), &project.top)?;
    std::fs::write(dir.join("src").join("core.v"), &project.core)?;
    std::fs::write(dir.join("info.yaml"), &project.info_yaml)?;
    std::fs::write(dir.join("docs").join("info.md"), &project.docs_info)?;
    Ok(())
}

/// Anything that can go wrong while assembling a submission.
#[derive(Debug)]
#[non_exhaustive]
pub enum BuildError {
    /// The pin map does not fit the die, or names a port that does not exist.
    Pins(Error),
    /// The core module could not be emitted.
    Core(String),
    /// The design rejected a graph operation.
    Ir(ferrite_lithic::Error),
    /// The process has no memory macro of the requested shape.
    NoSuchMacro {
        /// The process's name.
        pdk: String,
        /// The depth that was asked for.
        depth: u32,
        /// The word width that was asked for.
        width: u32,
    },
    /// A macro has a port this crate does not know how to connect.
    UnknownMacroPort {
        /// The macro's name.
        module: String,
        /// The port that could not be connected.
        port: String,
    },
    /// A file could not be written.
    Io(std::io::Error),
}

impl fmt::Display for BuildError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Pins(inner) => write!(f, "{inner}"),
            Self::Core(inner) => write!(f, "the core module could not be emitted: {inner}"),
            Self::Ir(inner) => write!(f, "{inner}"),
            Self::NoSuchMacro { pdk, depth, width } => write!(
                f,
                "the process {pdk} has no {depth}-word {width}-bit memory macro. \
                 The macros it does have are listed by \
                 `ferrite_lithic_pdk::Pdk::sram_macros`, with the depth and width \
                 of each, and with the area each one costs — which is the number \
                 that decides how many of them fit."
            ),
            Self::UnknownMacroPort { module, port } => write!(
                f,
                "the memory macro `{module}` has a port `{port}` that this crate \
                 does not know how to connect. Every port has to be connected, \
                 because an unconnected macro input is a floating input, and the \
                 foundry's own model stops the simulation on one of them."
            ),
            Self::Io(inner) => write!(f, "{inner}"),
        }
    }
}

impl std::error::Error for BuildError {}

impl From<Error> for BuildError {
    fn from(inner: Error) -> Self {
        Self::Pins(inner)
    }
}

impl From<ferrite_lithic::Error> for BuildError {
    fn from(inner: ferrite_lithic::Error) -> Self {
        Self::Ir(inner)
    }
}

impl From<std::io::Error> for BuildError {
    fn from(inner: std::io::Error) -> Self {
        Self::Io(inner)
    }
}
